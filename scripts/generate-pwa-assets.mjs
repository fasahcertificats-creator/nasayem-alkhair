import { createHash } from "node:crypto";
import {
  existsSync,
  readFileSync,
  readdirSync,
  statSync,
  writeFileSync
} from "node:fs";
import { extname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const scriptDirectory = fileURLToPath(new URL(".", import.meta.url));
const root = join(scriptDirectory, "..");
const generatorPath = fileURLToPath(import.meta.url);
const swTemplatePath = join(root, "src", "pwa", "sw-template.js");
const generatedRoutesPath = join(
  root,
  "src",
  "pwa",
  "offline-routes.generated.ts"
);
const generatedServiceWorkerPath = join(root, "public", "sw.js");
const categoriesPath = join(root, "data", "azkar", "categories.json");
const umrahStagesPath = join(root, "data", "umrah", "stages.json");
const excludedReleasePaths = new Set([
  "public/sw.js",
  "src/pwa/offline-routes.generated.ts"
]);
const excludedDirectoryNames = new Set([
  ".git",
  ".next",
  ".cache",
  "build",
  "coverage",
  "node_modules",
  "out"
]);
const binaryFileExtensions = new Set([
  ".gif",
  ".ico",
  ".jpeg",
  ".jpg",
  ".pdf",
  ".png",
  ".ttf",
  ".webp",
  ".woff",
  ".woff2"
]);
const temporaryFilePattern = /(?:~|\.(?:bak|old|orig|swp|temp|tmp))$/i;

const requiredStaticRoutes = [
  "/",
  "/prayer-times",
  "/azkar",
  "/tasbih",
  "/progress",
  "/umrah",
  "/miqat",
  "/services",
  "/more",
  "/privacy",
  "/terms",
  "/disclaimer",
  "/sources",
  "/support",
  "/offline"
];

function readJson(path) {
  return JSON.parse(readFileSync(path, "utf8"));
}

const azkarCategories = readJson(categoriesPath);
const umrahStages = readJson(umrahStagesPath);
const azkarRoutes = azkarCategories.map((category) => `/azkar/${category}`);
const umrahRoutes = [...umrahStages]
  .sort((first, second) => first.order - second.order)
  .map((stage) => `/umrah/${stage.slug}`);
const offlineRoutes = [
  ...requiredStaticRoutes,
  ...azkarRoutes,
  ...umrahRoutes
];

if (
  !azkarCategories.every(
    (category) => typeof category === "string" && category.length > 0
  ) ||
  !umrahStages.every(
    (stage) =>
      typeof stage.slug === "string" &&
      stage.slug.length > 0 &&
      Number.isFinite(stage.order)
  ) ||
  new Set(offlineRoutes).size !== offlineRoutes.length
) {
  throw new Error("The offline route inventory contains invalid or duplicate routes.");
}

function collectFiles(directory, output) {
  if (!existsSync(directory)) {
    return;
  }

  for (const name of readdirSync(directory).sort()) {
    const path = join(directory, name);
    const relativePath = getRelativePath(path);

    if (
      excludedReleasePaths.has(relativePath) ||
      excludedDirectoryNames.has(name) ||
      temporaryFilePattern.test(name)
    ) {
      continue;
    }

    if (statSync(path).isDirectory()) {
      collectFiles(path, output);
    } else {
      output.push(path);
    }
  }
}

function getRelativePath(path) {
  return relative(root, path).replaceAll("\\", "/");
}

function readCanonicalInput(path) {
  if (binaryFileExtensions.has(extname(path).toLowerCase())) {
    return readFileSync(path);
  }

  const normalizedText = readFileSync(path, "utf8").replace(/\r\n?/g, "\n");
  return Buffer.from(normalizedText, "utf8");
}

const releaseFiles = [];
for (const path of [
  join(root, "src"),
  join(root, "data"),
  join(root, "public", "pwa")
]) {
  collectFiles(path, releaseFiles);
}
for (const path of [
  join(root, "package.json"),
  join(root, "next.config.ts"),
  generatorPath,
  swTemplatePath
]) {
  if (existsSync(path) && !releaseFiles.includes(path)) {
    releaseFiles.push(path);
  }
}

const sourceHash = createHash("sha256");
for (const path of releaseFiles.sort((first, second) => {
  const firstRelativePath = getRelativePath(first);
  const secondRelativePath = getRelativePath(second);

  if (firstRelativePath < secondRelativePath) {
    return -1;
  }

  if (firstRelativePath > secondRelativePath) {
    return 1;
  }

  return 0;
})) {
  sourceHash.update(getRelativePath(path), "utf8");
  sourceHash.update("\0");
  sourceHash.update(readCanonicalInput(path));
  sourceHash.update("\0");
}
const sourceVersion = sourceHash.digest("hex").slice(0, 16);
const releaseVersion = `pwa-${sourceVersion}`;

const swTemplate = readFileSync(swTemplatePath, "utf8");
const serviceWorker = swTemplate
  .replace("__PWA_RELEASE_VERSION__", releaseVersion)
  .replace("__PWA_OFFLINE_ROUTES__", JSON.stringify(offlineRoutes));
const generatedRoutes = `/* This file is generated by scripts/generate-pwa-assets.mjs. */\n` +
  `export const PWA_RELEASE_VERSION = ${JSON.stringify(releaseVersion)} as const;\n` +
  `export const OFFLINE_ROUTES = ${JSON.stringify(offlineRoutes, null, 2)} as const;\n` +
  `export const OFFLINE_ROUTE_COUNT = OFFLINE_ROUTES.length;\n`;

writeFileSync(generatedServiceWorkerPath, serviceWorker, "utf8");
writeFileSync(generatedRoutesPath, generatedRoutes, "utf8");

console.log(
  `Generated PWA assets for ${releaseVersion} with ${offlineRoutes.length} offline routes.`
);
